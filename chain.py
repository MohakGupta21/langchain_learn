from dotenv import load_dotenv
from langchain.agents import create_agent
from langchain.tools import tool
from langchain_core.messages import HumanMessage
from langchain_openai import ChatOpenAI
from langchain_tavily import TavilySearch
load_dotenv()
from pydantic import BaseModel, Field
from typing import List

class Source(BaseModel):
    url: str = Field(description="The URL of the source")

class AgentResponse(BaseModel):
    answer: str = Field(description="The answer generated by the agent")
    sources: List[Source] = Field(description="The sources used by the agent")

tools = [TavilySearch()]

agent = create_agent(model=ChatOpenAI(model="gpt-4o", temperature=0), tools=tools, response_format=AgentResponse)

result = agent.invoke({"messages":HumanMessage("Search for three job openings for an AI software engineer in India")})

print(result["messages"][-1].content)